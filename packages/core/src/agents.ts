import { PAGE_SCHEMA, SPEC_SCHEMA, type Field } from "./schema.ts";

/**
 * What an agent is told about this repository's documentation.
 *
 * An agent handed a repository sees Markdown files and a `gitspec.yaml`. It has no way to
 * learn that the frontmatter has a required shape, that a statement in `Behaviour` needs
 * a permanent identifier, that a document absent from the navigation is invisible, or
 * that there is a command which would have told it all of this in under a second. So it
 * writes something the checker rejects, and finds out from a human hours later.
 *
 * `AGENTS.md` is where tools look for that, so this generates one — from `SPEC_SCHEMA`,
 * the same value the form renders and the checker enforces. A hand-written instruction
 * file drifts from the rules it describes; one generated from the rules cannot.
 */

export interface AgentsInput {
    /** Where documents live, from the configuration. */
    spaces: { key: string; title: string; directory?: string; summary?: string }[];
    /** The command this repository runs the checker with. */
    checkCommand: string;
    newCommand: string;
}

function fieldLine(field: Field): string {
    const type =
        field.type.kind === "enum"
            ? field.type.values.map((v) => `\`${v}\``).join(", ")
            : field.type.kind === "paths"
              ? "list of path globs, may be empty"
              : field.type.kind === "shaOrNull"
                ? "commit sha, or `null`"
                : field.type.kind === "date"
                  ? "`YYYY-MM-DD`"
                  : "text";
    return `| \`${field.key}\` | ${type} | ${field.required ? "yes" : "no"} | ${field.rule} | ${field.help ?? ""} |`;
}

export function agentsMarkdown(input: AgentsInput): string {
    const places = input.spaces
        .map((space) => {
            const where = space.directory
                ? `\`${space.directory.replace(/^\.\//, "").replace(/\/$/, "")}/\``
                : "the paths its configuration matches";
            const nav = space.summary ? `, with navigation in \`${space.summary}\`` : "";
            return `- **${space.title}** — ${where}${nav}.`;
        })
        .join("\n");

    return `# Documentation in this repository

<!-- Generated by GitSpec from its document schema. Edit the schema, not this file. -->

Documentation here is managed by [GitSpec](https://github.com/PasserBo/GitSpec): the
Markdown files in this repository are the source of truth, and a site is built from them.
There is no external wiki to update and no API to call — change the files.

## Before you commit a document

\`\`\`bash
${input.checkCommand}            # reports what is wrong, with the rule and the line
${input.checkCommand} --json     # the same findings, for a program to act on
\`\`\`

It exits non-zero when a document breaks a rule. Run it; do not wait for review to find
out. Every finding names the claim it comes from, and every claim is written down in the
specs under the directories below.

## Starting a document

\`\`\`bash
${input.newCommand} "Some title"
\`\`\`

This writes a document that already passes the checker and adds its line to the
navigation file. Prefer it to writing frontmatter by hand — a document missing from the
navigation is still served and is invisible, which is the quietest way to lose work.

## Where documents live

${places}

## The two kinds of document

A document declares its \`kind\`. **Only a \`spec\` has rules.** A \`page\` is prose and is
subject to none of what follows beyond carrying an \`id\`; \`kind\` defaults to \`page\`, so a
document that does not say otherwise is unchecked.

### A spec's frontmatter

| Key | Value | Required | Rule | Notes |
| --- | --- | --- | --- | --- |
${SPEC_SCHEMA.map(fieldLine).join("\n")}

A key outside this list is an error. Do **not** add \`created\` or \`updated\`: those are read
from the commit history, and a copy in the file would disagree with git.

### A page's frontmatter

| Key | Value | Required |
| --- | --- | --- |
${PAGE_SCHEMA.map((f) => `| \`${f.key}\` | ${f.type.kind === "enum" ? f.type.values.map((v) => `\`${v}\``).join(", ") : "text"} | no |`).join("\n")}

A page may carry any other key; nothing checks them.

### A spec's body

Exactly three top-level sections, in this order, none absent and any of them may be empty:

\`\`\`markdown
## Intent
## Behaviour
## Open questions
\`\`\`

**Only \`Behaviour\` is checked.** Every top-level bullet in it is a claim and carries a
permanent identifier in bold at the start of the line:

\`\`\`markdown
- **F-3** — \`status\` is one of \`draft\`, \`active\`, or \`superseded\`.
\`\`\`

- An identifier is unique within its spec and is **never reused or renumbered**, because
  reports, review comments and commit messages refer to it. It is also the document's
  anchor, so \`#F-3\` is a permanent link to that statement.
- A retired claim keeps its identifier and is marked \`(withdrawn)\` rather than deleted.
- A claim states something that is true or false of the code. Anything that cannot be
  contradicted by a change belongs in \`Intent\`.
- A nested bullet is part of the claim above it and needs no identifier of its own.

Prose in \`Behaviour\` is allowed and is not a claim. A bullet inside a fenced code block
is an example and is not a claim.

## How a change is made

One document, one pull request. The branch is derived from the document's id, so a second
edit to the same document appends to the open pull request rather than opening a rival
one. Nothing is merged automatically, and a change becomes authoritative when it merges —
not when it is saved.
`;
}
